# Maps before the Minotaur fight, where the Chamomile Sigil may not appear.
PRE_MINOTAUR = {9, 12, 13, 14, 15, 16, 18, 19, 20, 21, 22}
# Zones whose drops are randomized (src/payload/enemies.c).
DROP_ZONES = {9, 11, 12, 13, 14, 15, 16, 17, 22, 24, 25, 28, 30, 31, 32, 36, 40, 41, 48, 49, 50,
              51, 52, 53, 54, 55, 56}
PROGRESSION = range(0x1CA, 0x1EA)
SPAWN = 0x28


def room_keys(disc):
    """MPD number -> roomKey (zone << 8 | index in the zone's MPD list)."""
    by_lba = {e.lba: int(e.path[7:10]) for e in disc.files() if e.path.startswith('MAP/MAP')}
    keys = {}
    for e in sorted(disc.files(), key=lambda e: e.path):
        if e.path.startswith('MAP/ZONE') and e.path.endswith('.ZND'):
            zone = int(e.path[8:11])
            znd = disc.read_lba(e.lba, e.size)
            off, ln = struct.unpack_from('<II', znd, 0)
            for idx in range(ln // 8):
                mpd = by_lba.get(struct.unpack_from('<I', znd, off + idx * 8)[0])
                if mpd is not None:
                    keys.setdefault(mpd, (zone << 8) | idx)
    return keys


def room_slots(mpd, zone):
    """Eligible chest misc slots (bitmask) and eligible drop count, using the
    same tests as the payload: chest slot present on both difficulties (3) and
    not a vanilla key/sigil; drop on an enemy spawn in a randomized zone and
    not a vanilla key/sigil."""
    hdr = struct.unpack_from('<12I', mpd, 0)
    chest = 0
    if hdr[11] == 0x220:
        for i in range(3):
            iid, flags, _ = struct.unpack_from('<HBB', mpd, hdr[10] + 0x214 + i * 4)
            if flags == 3 and iid not in PROGRESSION:
                chest |= 1 << i
    drops = 0
    if zone in DROP_ZONES:
        for i in range(hdr[9] // SPAWN):
            s = mpd[hdr[8] + i * SPAWN:][:SPAWN]
            if s[0] == 0 and struct.unpack_from('<H', s, 0x1E)[0] not in PROGRESSION:
                drops += 1
    return chest, drops


def collect(disc):
    keys = room_keys(disc)
    rows = []
    for area, maps in enumerate(AREAS):
        for n in maps:
            if n not in keys:
                continue
            mpd = disc.read_file(f'MAP/MAP{n:03d}.MPD')
            chest, drops = room_slots(mpd, keys[n] >> 8)
            rows.append((keys[n], area, n in PRE_MINOTAUR, chest, drops))
    return rows


def emit(rows, out):
    lines = ['/* Generated by tools/gen_keyrooms.py from the vanilla disc. Do not edit. */',
             '#include "keys.h"', '', 'const keyRoom_t keyRooms[] = {']
    for key, area, pre, chest, drops in rows:
        lines.append(f'    {{ 0x{key:04X}, {area}, {int(pre)}, 0x{chest:X}, {drops} }},')
    lines += ['};', f'const int keyRoomCount = {len(rows)};', '']
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--vanilla', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    rows = collect(psxdisc.Disc(args.vanilla))
    assert max(r[4] for r in rows) <= 8, 'raise KEY_MAX_DRAWS in src/payload/keys.h'
    emit(rows, args.out)
    print(f'key rooms: {len(rows)} rooms, {sum(bin(r[3]).count("1") for r in rows)} chest slots, '
          f'{sum(r[4] for r in rows)} drops')


if __name__ == '__main__':
    main()
