"""Generate the chest stat tiers for "Balance item stats"
(build/gen/chesttiers.c, part of the battle overlay).

ChaoticBrave's Chests.cpp narrows the class, affinity, BEP and gem stat
ranges of chest equipment in three lists of maps (roughly early, middle and
late game); every other map uses the widest ranges. The payload knows rooms
by roomKey, so the map numbers are translated here."""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import psxdisc  # noqa: E402
from gen_keyrooms import room_keys  # noqa: E402

TIERS = [
    [18, 27, 409, 25, 26, 408, 32, 33, 37, 45, 50],
    [124, 175, 176, 177, 202, 203, 227, 241, 240, 261, 270, 274, 276],
    [254, 255, 259, 289, 292, 295, 306, 326, 331, 333, 336],
]


def collect(disc):
    keys = room_keys(disc)
    return sorted((keys[m], tier) for tier, maps in enumerate(TIERS) for m in maps if m in keys)


def emit(rows, out):
    lines = ['/* Generated by tools/gen_chesttiers.py from the vanilla disc. Do not edit. */',
             '#include "rando.h"', '', '/* roomKey << 2 | tier; rooms not listed are tier 3. */',
             'const u32 chestTiers[] = {']
    lines += [f'    0x{key:04X} << 2 | {tier},' for key, tier in rows]
    lines += ['};', f'const int chestTierCount = {len(rows)};', '']
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--vanilla', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    rows = collect(psxdisc.Disc(args.vanilla))
    emit(rows, args.out)
    print(f'chest tiers: {len(rows)} rooms of {sum(map(len, TIERS))} listed maps')


if __name__ == '__main__':
    main()
