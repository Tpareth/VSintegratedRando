END = 0xE7


def decode(data):
    out = []
    for b in data:
        if b == END:
            break
        out.append(TABLE[b] if TABLE[b] else f'<{b:02X}>')
    return ''.join(out)


def encode(text):
    out = bytearray()
    for ch in text:
        out.append(TABLE.index(ch))
    out.append(END)
    return bytes(out)
